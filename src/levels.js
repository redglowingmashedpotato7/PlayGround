export const TILE = T

export function tileToWorld(x, z) {
  return { x: (x - 13.5) * T, z: (z - 13.5) * T }
}

export function roomCenter(room) {
  return { x: room.x + room.w / 2, z: room.z + room.d / 2 }
}

export function buildGrid(level) {
  const W = 27, H = 27
  const grid = Array.from({ length: H }, () => Array(W).fill(1))
  for (const r of level.rooms) for (let z = r.z; z < r.z + r.d; z++) for (let x = r.x; x < r.x + r.w; x++) grid[z][x] = 0
  for (const c of level.corridors) for (let z = c.z; z < c.z + c.d; z++) for (let x = c.x; x < c.x + c.w; x++) grid[z][x] = 0
  return grid
}
